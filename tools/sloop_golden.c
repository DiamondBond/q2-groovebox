#include <stdio.h>
#include <stdint.h>
#include <string.h>
#define __attribute__(x)
#include "felucca_tables.h"
enum { G_BPM, G_FXFADE, G_DTIME, G_DFDBK, G_DCOLOR, G_DMIX, G_RSIZE, G_RDAMP, G_CRATE, G_CDEPTH, G_COUNT };
static struct {
    int16_t g[G_COUNT];
    uint8_t playing;
} song;
static volatile uint32_t clk_pos;
static int32_t thr_dly;
typedef struct { int32_t amp0, amp1; } vmod_t;
static uint32_t dly_samples(uint32_t d) { return (void)d, (uint32_t)FS * 30u / (uint32_t)song.g[G_BPM]; }
#include "dsp.c"
#include "fx_part.c"
#include "punch.c"
#include "fx_signal.h"

int main(void)
{
    printf("/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/sloop_golden.c: SLOOP's own output, one hash an effect. */\n");
    printf("static const unsigned fx_golden[%uu] = {", (unsigned)PUNCH_NFX);
    for (unsigned k = 0; k < PUNCH_NFX; k++) {
        int32_t l[CTL], r[CTL], dly[CTL], rev[CTL], wl[CTL], wr[CTL], cho[CTL] = {0};
        unsigned h = 2166136261u;
        memset(dly_buf, 0, sizeof dly_buf), memset(cho_buf, 0, sizeof cho_buf), memset(rev_line, 0, sizeof rev_line);
        memset(rev_ap, 0, sizeof rev_ap), memset(&fx, 0, sizeof fx), memset(punch_ring, 0, sizeof punch_ring);
        memset((void *)&punch, 0, sizeof punch);
        memset(rev_l, 0, sizeof rev_l), memset(rev_r, 0, sizeof rev_r);
        punch.req = punch.cur = -1, punch.fg = 8192, rev_frz = 0;
        song.g[G_BPM] = 120, song.g[G_FXFADE] = 0, song.g[G_DTIME] = 1, song.g[G_DFDBK] = 60, song.g[G_DCOLOR] = 70;
        song.g[G_DMIX] = 90, song.g[G_RSIZE] = 90, song.g[G_RDAMP] = 60, song.g[G_CRATE] = 40, song.g[G_CDEPTH] = 60;
        song.playing = 1;
        for (unsigned b = 0; b < GOLDEN_BLOCKS; b++) {
            clk_pos = b * CTL % 22050u * 120u;
            punch.req = b >= GOLDEN_ON && b < GOLDEN_OFF ? (int8_t)k : -1;
            golden_signal(b, l, r, dly, rev);
            punch_freeze_feed(rev, l, r, CTL);
            fx_buses(cho, dly, rev, wl, wr, CTL);
            for (unsigned i = 0; i < CTL; i++) l[i] += wl[i], r[i] += wr[i];
            punch_process(l, r, CTL);
            h = golden_hash(golden_hash(h, l), r);
        }
        printf("%s0x%08xu,", k % 6 ? " " : "\n    ", h);
    }
    printf("\n};\n");
    return 0;
}
