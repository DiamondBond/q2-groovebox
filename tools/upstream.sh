#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-only
# Regenerates what is lifted or rendered from upstream, at the pinned commits: src/sloop_tables.h,
# src/fx_golden.h, src/x0x, src/felucca, kits/909, kits/808 and kits/melodic. The build needs none of
# this. Needs cc, ffmpeg, python3 and network. tools/upstream.sh [WORKDIR]
set -e
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
WORK=${1:-$(mktemp -d)}
GEN=$WORK/gen
mkdir -p "$GEN"

fetch() { # DIR URL COMMIT
    [ -d "$WORK/$1" ] || git clone -q --filter=blob:none "$2" "$WORK/$1"
    git -C "$WORK/$1" checkout -q "$3"
}
fetch sloop https://github.com/isod89/sloop-fm1 bac9c05
fetch x0x https://github.com/charlesvestal/fm1-x0x a0d1a13
fetch felucca https://github.com/hugelton/Felucca a4f007c
fetch engines https://github.com/hugelton/Felucca-Engines d026007

# SLOOP: the four tables the lift reads, and its own output on the check's input
python3 -I "$WORK/sloop/tools/gen_tables.py" "$GEN/felucca_tables.h"
python3 -I - "$GEN/felucca_tables.h" "$ROOT/src/sloop_tables.h" <<'EOF'
import re, sys
s = open(sys.argv[1]).read()
head = ("/* SPDX-License-Identifier: GPL-3.0-only\n"
        " * Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments\n"
        " * Generated by SLOOP's tools/gen_tables.py at FS 44100 (tools/upstream.sh): the four tables the lift reads. */\n"
        "#include <stdint.h>\n")
parts = [re.search(r'static const \w+ ' + n + r'\[\d+\] = \{.*?\};\n', s, re.S).group(0)
         for n in ('SINE', 'LFO_INC', 'SVF_G', 'TANH_Q15')]
open(sys.argv[2], 'w').write('\n'.join([head] + parts))
EOF
sed -n '1,25p;194,306p' "$WORK/sloop/firmware/src/fx.c" > "$GEN/fx_part.c"
cc -std=gnu11 -O2 -w -I"$GEN" -I"$WORK/sloop/firmware/src" -I"$ROOT/src" -o "$GEN/sloop_golden" "$ROOT/tools/sloop_golden.c"
"$GEN/sloop_golden" > "$ROOT/src/fx_golden.h"

# X0X: the 909 and 808 models
python3 -I "$WORK/x0x/tools/gen_drum_samples.py" "$GEN/x0x_drum_samples.h"
D=$WORK/x0x/firmware/src/dsp
cc -std=gnu11 -O2 -w -I"$GEN" -I"$D" -o "$GEN/x0x_render" "$ROOT/tools/x0x_render.c" "$D/drum909.c" "$D/drum808.c" -lm
rm -rf "$ROOT/kits/909" "$ROOT/kits/808"
mkdir -p "$ROOT/kits/909" "$ROOT/kits/808"
"$GEN/x0x_render" "$ROOT/kits/909" "$ROOT/kits/808"

# the live machines: X0X's DSP and generator, Felucca-Engines and their generated tables
for f in drum909.c drum909.h drum909_dsp.h drum808.c drum808.h bass303.c bass303.h breaks.c breaks.h fxbus.c fxbus.h fastmath.h x0x_param.h; do
    cp "$D/$f" "$ROOT/src/x0x/dsp/"
done
cp "$GEN/x0x_drum_samples.h" "$GEN/x0x_drum_tables.h" "$ROOT/src/x0x/dsp/"
cp "$WORK"/x0x/firmware/src/seq/tb3po.c "$WORK"/x0x/firmware/src/seq/tb3po.h "$WORK"/x0x/firmware/src/seq/pattern.h "$ROOT/src/x0x/seq/"
cp "$WORK"/engines/src/* "$ROOT/src/felucca/"
python3 -I "$WORK/engines/tools/gen_engine_tables.py" "$ROOT/src/felucca/fe_tables.h"

# Felucca's CC0 samples: a second each, and five pitched copies to fill the pads
M=$ROOT/kits/melodic
S=$WORK/felucca/assets/samples-cc0
rm -rf "$M"
mkdir -p "$M"
n=0
sound() { # NAME FILE SEMITONES
    n=$((n + 1))
    rate=$(python3 -I -c "print(round(44100 * 2 ** ($3 / 12)))")
    ffmpeg -nostdin -v error -y -i "$S/$2" -t 1.2 -ac 1 \
        -af "asetrate=$rate,aresample=44100,atrim=0:1,afade=t=out:st=0.9:d=0.1" -c:a pcm_s16le -map_metadata -1 -bitexact \
        "$M/$(printf %02d $n) $1.wav"
}
sound 'Piano C1' PIANO/00_GPiano_sus_C1_v2_rr1_Player.wav 0
sound 'Piano C2' PIANO/01_GPiano_sus_C2_v2_rr1_Player.wav 0
sound 'Piano C3' PIANO/02_GPiano_sus_C3_v2_rr1_Player.wav 0
sound 'Piano E3' PIANO/02_GPiano_sus_C3_v2_rr1_Player.wav 4
sound 'Piano G3' PIANO/02_GPiano_sus_C3_v2_rr1_Player.wav 7
sound 'Piano C4' PIANO/03_GPiano_sus_C4_v2_rr1_Player.wav 0
sound 'Piano E4' PIANO/03_GPiano_sus_C4_v2_rr1_Player.wav 4
sound 'Piano G4' PIANO/03_GPiano_sus_C4_v2_rr1_Player.wav 7
sound 'Piano C5' PIANO/04_GPiano_sus_C5_v2_rr1_Player.wav 0
sound 'Flute C4' FLUTE/00_LDFlute_susvib_C4_v1_1.wav 0
sound 'Flute C5' FLUTE/01_LDFlute_susvib_C5_v1_1.wav 0
sound 'Flute G5' FLUTE/01_LDFlute_susvib_C5_v1_1.wav 7
sound 'Flute C6' FLUTE/02_LDFlute_susvib_C6_v1_1.wav 0
sound 'Sax A#1' 'SAX/00_BrettTenor_NV_Main_A#1_vl2_rr1.wav' 0
sound 'Sax A#2' 'SAX/01_BrettTenor_NV_Main_A#2_vl2_rr1.wav' 0
sound 'Sax A#3' 'SAX/02_BrettTenor_NV_Main_A#3_vl2_rr1.wav' 0
# the recordings are quiet and start late: to the front and up to a common peak, as the drums are
python3 -I - "$M" <<'PY'
import array, glob, sys, wave
for f in glob.glob(sys.argv[1] + '/*.wav'):
    with wave.open(f) as w:
        a = array.array('h', w.readframes(w.getnframes()))
    top = max(map(abs, a)) or 1
    start = next(i for i, x in enumerate(a) if abs(x) > top / 20)
    pcm = array.array('h', (int(x * 26000 / top) for x in a[start:]))
    with wave.open(f, 'wb') as w:
        w.setparams((1, 2, 44100, 0, 'NONE', ''))
        w.writeframes(pcm.tobytes())
PY
du -sh "$ROOT"/kits/*
